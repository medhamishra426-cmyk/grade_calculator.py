def get_grade(marks):
    if marks >= 90:
        return "A", "Outstanding! Keep up the excellent work!"
    elif marks >= 80:
        return "B", "Very good! Keep it up!"
    elif marks >= 70:
        return "C", "Good job! Push a little harder next time."
    elif marks >= 60:
        return "D", "Passed, but there's room to grow."
    else:
        return "F", "Don't give up. Review the topics and retry."


def get_valid_marks():
    while True:
        try:
            marks = float(input("Enter marks (0-100): "))
        except ValueError:
            print("Invalid input. Please enter a number.")
            continue

        if 0 <= marks <= 100:
            return marks
        print("Marks must be between 0 and 100.")


def main():
    name = input("Enter student name: ").strip()
    marks = get_valid_marks()
    grade, message = get_grade(marks)

    print(f"\nRESULT FOR {name.upper()}:")
    print(f"Marks: {marks:g}/100")
    print(f"Grade: {grade}")
    print(f"Message: {message}")


if __name__ == "__main__":
    main()